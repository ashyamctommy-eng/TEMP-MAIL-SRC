#!/usr/bin/env bash
#
# GoldenMail installer for VPS / bare-metal Linux.
#
#   sudo ./installer.sh
#   ./installer.sh --domain example.com --site-url https://mail.example.com \
#                  --mail-hostname mail.example.com --admin-user admin \
#                  --admin-pass 'strong-password' --yes
#
# Creates .env, installs dependencies, initialises the database and the first
# admin, and (optionally) installs a systemd service.
#
set -euo pipefail

APP_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$APP_DIR"

DOMAIN=""
SITE_URL=""
MAIL_HOSTNAME=""
ADMIN_USER="admin"
ADMIN_PASS=""
PORT="3000"
SMTP_PORT="25"
SMTP_ENABLED="1"
ASSUME_YES="0"
WITH_SYSTEMD="0"
SKIP_DEPS="0"

C_RESET="\033[0m"; C_GOLD="\033[38;5;179m"; C_DIM="\033[2m"; C_RED="\033[31m"; C_GREEN="\033[32m"

say()  { printf "${C_GOLD}▸${C_RESET} %s\n" "$*"; }
ok()   { printf "${C_GREEN}✓${C_RESET} %s\n" "$*"; }
warn() { printf "${C_RED}!${C_RESET} %s\n" "$*" >&2; }
die()  { warn "$*"; exit 1; }

usage() {
  cat <<EOF
GoldenMail installer

Usage: ./installer.sh [options]

  --domain <name>          Default mail domain to add (e.g. example.com)
  --site-url <url>         Public URL (e.g. https://mail.example.com)
  --mail-hostname <host>   MX target hostname (e.g. mail.example.com)
  --admin-user <name>      Admin username (default: admin)
  --admin-pass <pass>      Admin password (min 8 chars; generated if omitted)
  --port <n>               HTTP port (default: 3000)
  --smtp-port <n>          Inbound SMTP port (default: 25)
  --no-smtp                Do not start the built-in SMTP server
  --systemd                Install and start a systemd service (needs root)
  --skip-deps              Skip npm install
  -y, --yes                Non-interactive

The script is idempotent: an existing .env is kept, an existing admin is kept.
EOF
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --domain) DOMAIN="${2:-}"; shift 2 ;;
    --site-url) SITE_URL="${2:-}"; shift 2 ;;
    --mail-hostname) MAIL_HOSTNAME="${2:-}"; shift 2 ;;
    --admin-user) ADMIN_USER="${2:-}"; shift 2 ;;
    --admin-pass) ADMIN_PASS="${2:-}"; shift 2 ;;
    --port) PORT="${2:-}"; shift 2 ;;
    --smtp-port) SMTP_PORT="${2:-}"; shift 2 ;;
    --no-smtp) SMTP_ENABLED="0"; shift ;;
    --systemd) WITH_SYSTEMD="1"; shift ;;
    --skip-deps) SKIP_DEPS="1"; shift ;;
    -y|--yes) ASSUME_YES="1"; shift ;;
    -h|--help) usage; exit 0 ;;
    *) die "Unknown option: $1 (try --help)" ;;
  esac
done

# ---------------------------------------------------------------- requirements

command -v node >/dev/null 2>&1 || die "Node.js is not installed. Install Node 22.5+ first: https://nodejs.org"
command -v npm  >/dev/null 2>&1 || die "npm is not installed."

NODE_VERSION="$(node -p 'process.versions.node')"
NODE_MAJOR="${NODE_VERSION%%.*}"
NODE_REST="${NODE_VERSION#*.}"
NODE_MINOR="${NODE_REST%%.*}"

if (( NODE_MAJOR < 22 || (NODE_MAJOR == 22 && NODE_MINOR < 5) )); then
  die "Node $NODE_VERSION found, but 22.5+ is required (built-in node:sqlite)."
fi
ok "Node $NODE_VERSION"

if [[ "$NODE_MAJOR" -lt 24 ]]; then
  warn "Node 22 is supported but will print an experimental warning for node:sqlite."
fi

# ------------------------------------------------------------------- prompts

if [[ "$ASSUME_YES" != "1" && -t 0 ]]; then
  echo
  say "Configuration (Enter accepts the default)"
  if [[ -z "$DOMAIN" ]]; then
    read -r -p "  Default domain [skip]: " DOMAIN || true
  fi
  if [[ -z "$SITE_URL" ]]; then
    read -r -p "  Public site URL [http://localhost:$PORT]: " SITE_URL || true
  fi
  if [[ -z "$MAIL_HOSTNAME" ]]; then
    read -r -p "  Mail hostname (MX target) [mail.localhost]: " MAIL_HOSTNAME || true
  fi
  read -r -p "  Admin username [$ADMIN_USER]: " input_user || true
  ADMIN_USER="${input_user:-$ADMIN_USER}"
  if [[ -z "$ADMIN_PASS" ]]; then
    read -r -s -p "  Admin password [auto-generate]: " ADMIN_PASS || true
    echo
  fi
fi

SITE_URL="${SITE_URL:-http://localhost:$PORT}"
MAIL_HOSTNAME="${MAIL_HOSTNAME:-mail.localhost}"

[[ -z "$ADMIN_PASS" ]] && ADMIN_PASS="$(node -e "console.log(require('crypto').randomBytes(9).toString('base64url'))")"
[[ ${#ADMIN_PASS} -lt 8 ]] && die "Admin password must be at least 8 characters."

# ---------------------------------------------------------------------- .env

if [[ -f .env ]]; then
  ok ".env already exists — keeping it"
  # shellcheck disable=SC1091
  set -a; . ./.env; set +a
  # Values from .env are now in the environment; keep the CLI port if provided.
  PORT="${PORT:-3000}"
else
  say "Writing .env"
  INGEST_SECRET="$(node -e "console.log(require('crypto').randomBytes(24).toString('hex'))")"
  cat > .env <<EOF
# Generated by installer.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
PORT=$PORT
HOST=0.0.0.0
SITE_URL=$SITE_URL
TRUST_PROXY=1
SECURE_COOKIES=$([[ "$SITE_URL" == https://* ]] && echo 1 || echo 0)

DATA_DIR=./data

SMTP_ENABLED=$SMTP_ENABLED
SMTP_PORT=$SMTP_PORT
SMTP_HOST=0.0.0.0
SMTP_MAX_MB=25
MAX_ATTACHMENT_MB=10

ADMIN_USER=$ADMIN_USER
# ADMIN_PASSWORD is intentionally not stored; it is passed to the setup step only.
SESSION_HOURS=12

MAIL_HOSTNAME=$MAIL_HOSTNAME
DEFAULT_DOMAIN=$DOMAIN

INGEST_SECRET=$INGEST_SECRET
EOF
  chmod 600 .env
  ok ".env created (chmod 600)"
fi

mkdir -p data/attachments data/tmp

# --------------------------------------------------------------------- deps

if [[ "$SKIP_DEPS" != "1" ]]; then
  say "Installing npm dependencies (production only)"
  npm install --omit=dev --no-audit --no-fund
  ok "Dependencies installed"
fi

# ----------------------------------------------------------------- bootstrap

say "Initialising database and admin account"
SETUP_JSON="$(
  ADMIN_USER="$ADMIN_USER" \
  ADMIN_PASSWORD="$ADMIN_PASS" \
  SITE_URL="$SITE_URL" \
  MAIL_HOSTNAME="$MAIL_HOSTNAME" \
  DEFAULT_DOMAIN="$DOMAIN" \
  node server/install-setup.js
)"
echo "$SETUP_JSON" | node -e '
  let raw = "";
  process.stdin.on("data", d => raw += d).on("end", () => {
    const r = JSON.parse(raw.trim());
    if (!r.ok) { console.error(r.error); process.exit(1); }
    console.log("  admin user:", r.username);
    if (r.createdAdmin) console.log("  admin password:", r.password);
    if (r.domain) console.log("  domain:", r.domain);
    for (const w of r.warnings || []) console.log("  warning:", w);
  });
'

# ------------------------------------------------------------------ port 25

if [[ "$SMTP_ENABLED" == "1" && "$SMTP_PORT" -lt 1024 ]]; then
  if [[ "$(id -u)" -eq 0 ]]; then
    NODE_BIN="$(command -v node)"
    if setcap 'cap_net_bind_service=+ep' "$NODE_BIN" 2>/dev/null; then
      ok "Granted CAP_NET_BIND_SERVICE to $NODE_BIN (port $SMTP_PORT)"
    else
      warn "Could not setcap on $NODE_BIN. Run as root or use a port >1024."
    fi
  else
    warn "Port $SMTP_PORT needs root/CAP_NET_BIND_SERVICE. Re-run with sudo, or use --smtp-port 2525."
  fi
fi

# ------------------------------------------------------------------- systemd

if [[ "$WITH_SYSTEMD" == "1" ]]; then
  [[ "$(id -u)" -eq 0 ]] || die "--systemd requires root."
  RUN_USER="${SUDO_USER:-$(id -un)}"
  NODE_BIN="$(command -v node)"
  say "Installing systemd service (user: $RUN_USER)"
  cat > /etc/systemd/system/goldenmail.service <<EOF
[Unit]
Description=GoldenMail temp mail
After=network.target

[Service]
Type=simple
WorkingDirectory=$APP_DIR
EnvironmentFile=$APP_DIR/.env
ExecStart=$NODE_BIN server/index.js
User=$RUN_USER
AmbientCapabilities=CAP_NET_BIND_SERVICE
Restart=always
RestartSec=3
NoNewPrivileges=true
PrivateTmp=true

[Install]
WantedBy=multi-user.target
EOF
  systemctl daemon-reload
  systemctl enable --now goldenmail
  ok "Service goldenmail started"
fi

# ------------------------------------------------------------------- summary

echo
printf "${C_GOLD}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━${C_RESET}\n"
printf "${C_GOLD} GoldenMail installed${C_RESET}\n"
printf "${C_GOLD}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━${C_RESET}\n"
echo "  App directory : $APP_DIR"
echo "  Public site   : $SITE_URL"
echo "  Admin panel   : $SITE_URL/admin"
echo "  Admin user    : $ADMIN_USER"
if printf '%s' "$SETUP_JSON" | grep -q '"createdAdmin":true'; then
  echo "  Admin pass    : (printed above — save it now)"
fi
echo
echo "  Next steps:"
echo "   1. Point an A record for $MAIL_HOSTNAME at this server."
echo "   2. Add MX for your domain -> $MAIL_HOSTNAME (priority 10)."
echo "   3. Add SPF:  v=spf1 mx ~all   and DMARC:  v=DMARC1; p=none"
echo "   4. Start the app:  npm start"
echo "      or with systemd: sudo systemctl status goldenmail"
echo
if [[ "$WITH_SYSTEMD" != "1" ]]; then
  echo "  Tip: re-run with sudo --systemd to install it as a service."
fi
